// Stamps the app version: a hash of every file the service worker caches (the app shell) plus
// the date it last changed. Run `npm run stamp` after changing app files and commit the result;
// tests/unit/version.test.js fails while the stamp is out of date.
//
// Writes:
//  - js/version.js  APP_VERSION and APP_BUILD_HASH, shown in the app;
//  - version.json   what the app fetches (never cached) to look for a newer deployment;
//  - sw.js          the CACHE_VERSION line, so every release is a new service worker with its own
//                   cache and the browsers notice the update.

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const VERSION_JS = 'js/version.js';
const VERSION_JSON = 'version.json';
const SW = 'sw.js';
const TEXT_FILE = /\.(js|css|html|json|svg)$/;

const read = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8');

/** The files that make up the app: the service worker's APP_SHELL without the version file. */
function appShell() {
    const list = read(SW).match(/const APP_SHELL = (\[[\s\S]*?\]);/)[1];

    return Function(`return ${list}`)().filter((entry) => entry !== './' && entry !== VERSION_JS);
}

/** SHA-256 over the names and contents of the app files (line endings do not matter). */
function computeBuildHash() {
    const hash = crypto.createHash('sha256');

    appShell().forEach((entry) => {
        const bytes = fs.readFileSync(path.join(ROOT, entry));
        const content = TEXT_FILE.test(entry)
            ? Buffer.from(bytes.toString('utf8').replace(/\r\n/g, '\n'))
            : bytes;

        hash.update(`${entry}\0`);
        hash.update(content);
        hash.update('\0');
    });

    return hash.digest('hex');
}

const pick = (text, pattern) => (text.match(pattern) || [])[1] || '';

/** What the three stamped files say right now. */
function readStamp() {
    const js = fs.existsSync(path.join(ROOT, VERSION_JS)) ? read(VERSION_JS) : '';
    const json = fs.existsSync(path.join(ROOT, VERSION_JSON)) ? read(VERSION_JSON) : '{}';
    let parsed = {};

    try {
        parsed = JSON.parse(json);
    } catch {
        // A damaged version.json simply counts as out of date.
    }

    return {
        version: pick(js, /APP_VERSION = '([^']*)'/),
        hash: pick(js, /APP_BUILD_HASH = '([0-9a-f]*)'/),
        json: parsed,
        cache: pick(read(SW), /const CACHE_VERSION = '([^']*)'/),
    };
}

const cacheName = (hash) => `fm-${hash.slice(0, 7)}`;

function isUpToDate() {
    const hash = computeBuildHash();
    const stamp = readStamp();

    return (
        stamp.hash === hash &&
        stamp.version !== '' &&
        stamp.json.version === stamp.version &&
        stamp.json.hash === hash &&
        stamp.cache === cacheName(hash)
    );
}

const today = () =>
    new Date().toLocaleDateString('sv-SE', { timeZone: 'Asia/Ho_Chi_Minh' }).replace(/-/g, '.');

/** Rewrite the stamped files; the date only moves when the content really changed. */
function stamp() {
    const hash = computeBuildHash();
    const current = readStamp();
    const version =
        current.hash === hash && current.version
            ? current.version
            : `${today()}-${hash.slice(0, 7)}`;

    fs.writeFileSync(
        path.join(ROOT, VERSION_JS),
        `// Generated by scripts/stamp-version.js (npm run stamp): do not edit by hand.\n` +
            `const APP_VERSION = '${version}';\n` +
            `const APP_BUILD_HASH = '${hash}';\n`,
    );
    fs.writeFileSync(
        path.join(ROOT, VERSION_JSON),
        `${JSON.stringify({ version, hash }, null, 4)}\n`,
    );

    const sw = read(SW);
    const next = sw.replace(
        /const CACHE_VERSION = '[^']*';/,
        `const CACHE_VERSION = '${cacheName(hash)}';`,
    );

    if (next === sw && !sw.includes(`const CACHE_VERSION = '${cacheName(hash)}';`)) {
        throw new Error('Không tìm thấy dòng CACHE_VERSION trong sw.js.');
    }

    fs.writeFileSync(path.join(ROOT, SW), next);

    return version;
}

module.exports = { appShell, computeBuildHash, readStamp, isUpToDate, stamp, cacheName };

if (require.main === module) {
    if (process.argv.includes('--check')) {
        if (!isUpToDate()) {
            console.error('Phiên bản chưa được đóng dấu lại. Chạy `npm run stamp` rồi commit.');
            process.exit(1);
        }

        console.log(`Phiên bản đã đúng: ${readStamp().version}`);
    } else {
        console.log(`Phiên bản: ${stamp()}`);
    }
}
